var (
	errNotSelector = errors.New("expression is not a selector or ident")
	errNotFunc     = errors.New("expression is not a function type")
	errNotFound    = errors.New("imported package not found")
	errConfused    = errors.New("too many package aliases")
)

type gen struct {
	dirName string
	name    string
	pkg     *packages.Package
	spec    *ast.TypeSpec
	out     *strings.Builder
	top     *strings.Builder
	imports map[string]*packages.Package
	byPath  map[string]string
	tc      *typeContext

	typeName string
}

type typeContext struct {
	pkg     *packages.Package
	imports fileImports
}

type fileImports map[string]*packages.Package

func newTypeContext(file *ast.File, pkg *packages.Package) *typeContext {
	imports := make(fileImports)
	for _, i := range file.Imports {
		var name, value string
		value, _ = strconv.Unquote(i.Path.Value)
		if i.Name != nil {
			name = i.Name.Name
		} else {
			name = path.Base(value)
		}
		imports[name] = pkg.Imports[value]
	}

	return &typeContext{
		pkg:     pkg,
		imports: imports,
	}
}

func (tc *typeContext) getImport(name string) *packages.Package {
	if pkg, ok := tc.imports[name]; ok {
		return pkg
	}
	return nil
}

func newGen(dirName, name string, file *ast.File, pkg *packages.Package, spec *ast.TypeSpec) *gen {
	return &gen{
		dirName: dirName,
		name:    name,
		pkg:     pkg,
		spec:    spec,
		top:     &strings.Builder{},
		out:     &strings.Builder{},
		imports: map[string]*packages.Package{},
		byPath: map[string]string{
			"github.com/zugcat/zrpc": "zrpc",
		},
		tc: newTypeContext(file, pkg),
	}
}

func (g *gen) writePreamble() {
	g.top.WriteString("// Code generated by zrpcgen DO NOT EDIT\n")
}

func (g *gen) writePackageName(name string) {
	fmt.Fprintf(g.top, "package %s\n\n", name)
}

func (g *gen) writeImports() {
	g.top.WriteString("import (\n")
	g.top.WriteString("\tzrpc \"github.com/zugcat/zrpc\"\n")

	for k, v := range g.imports {
		fmt.Fprintf(g.top, "\t%s %s\n", k, strconv.Quote(v.PkgPath))
	}

	g.top.WriteString(")\n\n")
}

func (g *gen) addImport(pkg *packages.Package, name string) (string, error) {
	if n, ok := g.byPath[pkg.PkgPath]; ok {
		// we already know it, maybe as a different import name
		return n, nil
	}

	if _, ok := g.imports[name]; ok {
		// we already have something else imported as name
		var newName string
		for n := range 10 {
			newName = fmt.Sprintf("%s%d", name, n)
			if _, ok := g.imports[newName]; !ok {
				break
			}
			newName = ""
		}

		if newName == "" {
			return "", fmt.Errorf("%w: %s", errConfused, name)
		}

		g.byPath[pkg.PkgPath] = pkg.PkgPath
		g.imports[newName] = pkg

		return newName, nil
	}

	g.byPath[pkg.PkgPath] = name
	g.imports[name] = pkg

	return name, nil
}

// evalType fixes up and potentially adds imports
func (g *gen) evalType(tc *typeContext, e ast.Expr) (o ast.Expr, err error) {
	defer func() {
		if err != nil {
			err = fmt.Errorf("%v: %w", g.pkg.Fset.Position(e.Pos()), err)
		}
	}()

	switch e := e.(type) {
	case *ast.Ident:
		r, _ := utf8.DecodeRuneInString(e.Name)
		if unicode.IsUpper(r) {
			if tc.pkg.Dir != g.dirName {
				name, err := g.addImport(tc.pkg, tc.pkg.Name)
				if err != nil {
					return nil, err
				}
				return &ast.SelectorExpr{
					X: &ast.Ident{
						Name: name,
					},
					Sel: e,
				}, nil
			}
		}

	case *ast.SelectorExpr:
		if ident, ok := e.X.(*ast.Ident); ok {
			if pkg := tc.getImport(ident.Name); pkg != nil {
				ident.Name, err = g.addImport(pkg, ident.Name)
				if err != nil {
					return nil, err
				}
			} else {
				return nil, fmt.Errorf("%w: %s", errNotFound, ident.Name)
			}
		}

	case *ast.StarExpr:
		e.X, err = g.evalType(tc, e.X)

	case *ast.ArrayType:
		e.Elt, err = g.evalType(tc, e.Elt)

	case *ast.MapType:
		e.Key, err = g.evalType(tc, e.Key)
		if err == nil {
			e.Value, err = g.evalType(tc, e.Value)
		}

	case *ast.IndexExpr:
		e.X, err = g.evalType(tc, e.X)
		if err == nil {
			e.Index, err = g.evalType(tc, e.Index)
		}

	case *ast.IndexListExpr:
		for n, i := range e.Indices {
			e.Indices[n], err = g.evalType(tc, i)
			if err != nil {
				break
			}
		}
	}

	return e, err
}

func (g *gen) typeExpr(tc *typeContext, e ast.Expr) (string, error) {
	e, err := g.evalType(tc, e)
	if err != nil {
		return "", err
	}

	s := &strings.Builder{}
	err = printer.Fprint(s, g.pkg.Fset, e)
	return s.String(), err
}

func (g *gen) writeStruct() error {
	g.typeName = fmt.Sprintf("%sStub", g.spec.Name.Name)

	if g.spec.Doc != nil {
		for _, comment := range g.spec.Doc.List {
			fmt.Fprintf(g.out, "%s\n",
				strings.ReplaceAll(comment.Text, g.spec.Name.Name, g.typeName),
			)
		}
	}
	fmt.Fprintf(g.out, "type %s", g.typeName)

	var typeParams []string
	if tp := g.spec.TypeParams; tp != nil {
		g.out.WriteRune('[')
		for n, field := range tp.List {
			if n > 0 {
				g.out.WriteString(", ")
			}
			for n, name := range field.Names {
				if n > 0 {
					g.out.WriteString(", ")
				}
				g.out.WriteString(name.Name)
				typeParams = append(typeParams, name.Name)
			}
			g.out.WriteRune(' ')
			typeName, err := g.typeExpr(g.tc, field.Type)
			if err != nil {
				return err
			}
			g.out.WriteString(typeName)
		}
		g.out.WriteRune(']')
	}

	if len(typeParams) > 0 {
		g.typeName += "["
		for n, t := range typeParams {
			if n > 0 {
				g.typeName += ","
			}
			g.typeName += t
		}
		g.typeName += "]"
	}

	g.out.WriteString(" struct {\n")
	g.out.WriteString("\t*zrpc.Object\n")
	g.out.WriteString("}\n\n")

	return nil
}

func (g *gen) writeMethods(tc *typeContext, ts *ast.TypeSpec) error {
	for _, method := range ts.Type.(*ast.InterfaceType).Methods.List {
		if len(method.Names) == 0 {
			pkg := tc.pkg

			var ident *ast.Ident
			var ok bool

			switch x := method.Type.(type) {
			case *ast.SelectorExpr:
				ident, ok = x.X.(*ast.Ident)
				if !ok {
					return fmt.Errorf(
						"%v: %w",
						g.pkg.Fset.Position(x.Pos()),
						errNotSelector,
					)
				}
				pkg = tc.getImport(ident.Name)
				if pkg == nil {
					return fmt.Errorf(
						"%v: %w: package %s not found",
						tc.pkg.Fset.Position(x.Pos()),
						errNotFound, ident.Name)
				}
				ident = x.Sel

			case *ast.Ident:
				ident = x

			default:
				return fmt.Errorf(
					"%v: %w",
					g.pkg.Fset.Position(x.Pos()),
					errNotSelector,
				)
			}

			ts, file, err := locate(ident.Name, pkg)
			if err != nil {
				return fmt.Errorf(
					"%v: %w",
					pkg.Fset.Position(method.Pos()),
					err,
				)
			}
			if ts == nil {
				return fmt.Errorf("%v: %w: %s.%s",
					pkg.Fset.Position(method.Pos()),
					errNotFound, pkg.Name, ident.Name)
			}
			if err := g.writeMethods(newTypeContext(file, pkg), ts); err != nil {
				return err
			}

			continue
		}

		if method.Doc != nil {
			for _, comment := range method.Doc.List {
				fmt.Fprintf(g.out, "%s\n", comment.Text)
			}
		}
		name := method.Names[0].Name
		fmt.Fprintf(g.out, "func (x %s)%s(", g.typeName, name)
		f, ok := method.Type.(*ast.FuncType)
		if !ok {
			return fmt.Errorf("%v: %w",
				g.pkg.Fset.Position(method.Pos()),
				errNotFunc,
			)
		}

		n := 0
		for _, in := range f.Params.List {
			for range max(1, len(in.Names)) {
				if n > 0 {
					g.out.WriteString(", ")
				}

				arg := fmt.Sprintf("_a%d", n)
				fmt.Fprintf(g.out, "%s ", arg)

				typeName, err := g.typeExpr(tc, in.Type)
				if err != nil {
					return err
				}

				g.out.WriteString(typeName)
				n++
			}
		}
		g.out.WriteString(") ")

		var returns []string
		errRet := -1

		if f.Results != nil {
			g.out.WriteRune('(')
			for n, out := range f.Results.List {
				if n > 0 {
					g.out.WriteString(", ")
				}
				typeName, err := g.typeExpr(tc, out.Type)
				if err != nil {
					return err
				}

				fmt.Fprintf(g.out, "_r%d %s", n, typeName)
				returns = append(returns, typeName)
				if typeName == "error" {
					errRet = n
				}
			}
			g.out.WriteRune(')')
		}

		g.writeBody(name, n, returns, errRet)
	}

	return nil
}

func (g *gen) writeBody(name string, ins int, returns []string, errRet int) {
	g.out.WriteString("{\n")

	fmt.Fprintf(g.out, "rv, err := x.Object.Call(%s", strconv.Quote(name))
	for i := range ins {
		g.out.WriteString(", ")
		fmt.Fprintf(g.out, "_a%d", i)
	}
	g.out.WriteString(")\n")

	fmt.Fprintf(g.out, "if err == nil && len(rv) != %d {\n", len(returns))
	g.out.WriteString("err = zrpc.ErrBadResponse\n}\n")
	g.out.WriteString("if err == nil {\n")
	for n, r := range returns {
		fmt.Fprintf(g.out, "_r%d, _ = rv[%d].(%s)\n", n, n, r)
	}
	g.out.WriteString("}\n")

	if errRet < 0 {
		g.out.WriteString("_ = err // no error return\n")
	} else {
		g.out.WriteString("if err != nil {\n")
		fmt.Fprintf(g.out, "_r%d=err\n}\n", errRet)
	}

	g.out.WriteString("return\n}\n\n")
}

func (g *gen) write(w io.Writer, pkgName string) error {
	if err := g.writeStruct(); err != nil {
		return err
	}
	if err := g.writeMethods(g.tc, g.spec); err != nil {
		return err
	}

	g.writePreamble()
	g.writePackageName(pkgName)
	g.writeImports()

	fset := token.NewFileSet()

	buf := &bytes.Buffer{}
	buf.Write([]byte(g.top.String()))
	g.top = nil
	buf.Write([]byte(g.out.String()))
	g.out = nil

	file, err := parser.ParseFile(fset, "", buf.Bytes(), parser.ParseComments)
	if err != nil {
		return err
	}
	return format.Node(w, fset, file)

}
